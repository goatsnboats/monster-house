"""Readable requirement pages: docs/requirements/pages/<prefix>.md, one per subsystem.

Each requirement gets its own heading (so the docs site's comment button sits on every
requirement) and a short card instead of the wide matrix in trace.md. Generated by
tools/reqs/check.py; edit the YAML, never these pages.
"""

from __future__ import annotations

from typing import Dict

from tools.reqs.checks import allocations, children_of, events_for, expected_file
from tools.reqs.load import Model

PAGES_DIR = "docs/requirements/pages"
NOTE = ("> Generated by `tools/reqs/check.py` from `{file}`; edit that file, not this page. "
        "Matrix and coverage: [trace.md](../trace.md).")


def _cell(text) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _links(model: Model, ids) -> str:
    return ", ".join(f"[{i}]({model.subsystem_of(i).lower()}.md)" for i in ids) or "—"


def page(model: Model, prefix: str) -> str:
    info = model.prefixes[prefix]
    ids = sorted(rid for rid in model.reqs if model.subsystem_of(rid) == prefix)
    lines = [f"# {prefix} — {info['name']} requirements", "", NOTE.format(file=f"docs/requirements/{expected_file(prefix)}"),
             "", f"{len(ids)} requirements.", ""]
    for rid in ids:
        r = model.reqs[rid]
        lines += [f"## {rid}", "", _cell(r.get("text", "")), "", "| | |", "|---|---|",
                  f"| Type, stage, status | {r.get('type')}, stage {r.get('stage')}, {r.get('status')} |"]
        if prefix == "SYS":
            lines.append(f"| Children | {_links(model, children_of(model, rid))} |")
            if r.get("decomposition"):
                lines.append(f"| How it splits | {_cell(r['decomposition'])} |")
        else:
            lines.append(f"| Derives from | {_links(model, r.get('derives_from') or [])} |")
            lines.append(f"| Allocated to | {', '.join(f'`{c}`' for c in allocations(r)) or '—'} |")
            if r.get("allocation_rationale"):
                lines.append(f"| Why there | {_cell(r['allocation_rationale'])} |")
        if r.get("icd"):
            lines.append(f"| Interface | {r['icd']} |")
        events = ", ".join(events_for(model, rid)) or "—"
        lines.append(f"| Verified by | {r.get('verify')} ({events}) |")
        if isinstance(r.get("basis"), dict):
            lines.append(f"| Basis | {r['basis'].get('method')}: {_cell(r['basis'].get('ref', ''))} |")
        if r.get("rationale"):
            lines.append(f"| Rationale | {_cell(r['rationale'])} |")
        if r.get("notes"):
            lines.append(f"| Notes | {_cell(r['notes'])} |")
        lines.append(f"| Source | {_cell(r.get('source', ''))} |")
        lines.append("")
    return "\n".join(lines)


def render_all(model: Model) -> Dict[str, str]:
    """{file name: content} for every prefix with requirements, plus an index."""
    pages = {}
    index = ["# Requirements by subsystem", "", NOTE.format(file="docs/requirements/*.yaml"), "",
             "| Subsystem | Requirements |", "|---|---|"]
    for prefix, info in model.prefixes.items():
        count = sum(1 for rid in model.reqs if model.subsystem_of(rid) == prefix)
        if not count:
            continue
        name = f"{prefix.lower()}.md"
        pages[name] = page(model, prefix)
        index.append(f"| [{prefix} — {info['name']}]({name}) | {count} |")
    pages["README.md"] = "\n".join(index) + "\n"
    return pages
