"""Readable pages made from the YAML: one per subsystem's requirements, one for the
verification events (docs/requirements/pages/), and one for the components
(docs/architecture/components.md).

Each requirement, event and component gets its own heading (so the docs site's comment
button sits on every one, and other pages can link straight to it) and a short card
instead of the wide matrix in trace.md. Generated by tools/reqs/check.py; edit the YAML,
never these pages.
"""

from __future__ import annotations

from typing import Dict

from tools.reqs.checks import allocations, children_of, component_page, events_for, expected_file
from tools.reqs.load import Model

PAGES_DIR = "docs/requirements/pages"
COMPONENTS_PAGE = "docs/architecture/components.md"
NOTE = ("> Generated by `tools/reqs/check.py` from `{file}`; edit that file, not this page. "
        "Matrix and coverage: [trace.md](../trace.md).")
EVENTS_PAGE = "ve.md"


def _cell(text) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _links(model: Model, ids, folder: str = "") -> str:
    """Requirement IDs as links to their headings; folder is the path to pages/ from the page."""
    return ", ".join(f"[{i}]({folder}{model.subsystem_of(i).lower()}.md#{i.lower()})" for i in ids) or "—"


def _event_links(ids) -> str:
    return ", ".join(f"[{e}]({EVENTS_PAGE}#{e.lower()})" for e in ids) or "—"


def page(model: Model, prefix: str) -> str:
    info = model.prefixes[prefix]
    ids = sorted(rid for rid in model.reqs if model.subsystem_of(rid) == prefix)
    lines = [f"# {prefix} — {info['name']} requirements", "", NOTE.format(file=f"docs/requirements/{expected_file(prefix)}"),
             "", f"{len(ids)} requirements.", ""]
    for rid in ids:
        r = model.reqs[rid]
        lines += [f"## {rid}", "", _cell(r.get("text", "")), "", "| | |", "|---|---|",
                  f"| Type, stage, status | {r.get('type')}, stage {r.get('stage')}, {r.get('status')} |"]
        if prefix == "SYS":
            lines.append(f"| Children | {_links(model, children_of(model, rid))} |")
            if r.get("decomposition"):
                lines.append(f"| How it splits | {_cell(r['decomposition'])} |")
        else:
            lines.append(f"| Derives from | {_links(model, r.get('derives_from') or [])} |")
            lines.append(f"| Allocated to | {', '.join(f'[`{c}`](../../architecture/components.md#{c})' for c in allocations(r)) or '—'} |")
            if r.get("allocation_rationale"):
                lines.append(f"| Why there | {_cell(r['allocation_rationale'])} |")
        if r.get("icd"):
            lines.append(f"| Interface | {r['icd']} |")
        events = _event_links(events_for(model, rid))
        lines.append(f"| Verified by | {r.get('verify')} ({events}) |")
        if isinstance(r.get("basis"), dict):
            lines.append(f"| Basis | {r['basis'].get('method')}: {_cell(r['basis'].get('ref', ''))} |")
        if r.get("rationale"):
            lines.append(f"| Rationale | {_cell(r['rationale'])} |")
        if r.get("notes"):
            lines.append(f"| Notes | {_cell(r['notes'])} |")
        lines.append(f"| Source | {_cell(r.get('source', ''))} |")
        lines.append("")
    return "\n".join(lines)


def events_page(model: Model) -> str:
    """Every verification event, one heading each, with the requirements it covers."""
    lines = ["# VE — Verification events", "",
             NOTE.format(file="docs/requirements/verification.yaml") + " Approach: [verification-plan.md](../verification-plan.md).",
             "", f"{len(model.events)} events.", ""]
    for eid, e in model.events.items():
        lines += [f"## {eid}", "", f"**{_cell(e.get('name', ''))}**", "", "| | |", "|---|---|",
                  f"| Stage, method | {e.get('stage')}, {e.get('method')} |",
                  f"| Where | {_cell(e.get('where', ''))} |",
                  f"| How | {_cell(e.get('how', ''))} |",
                  f"| Pass | {_cell(e.get('pass', ''))} |",
                  f"| Covers | {_links(model, [r for r in e.get('covers') or [] if r in model.reqs])} |", ""]
    return "\n".join(lines)


def _value(v) -> str:
    """A YAML value in one table cell."""
    if isinstance(v, dict):
        return "; ".join(f"{k}: {_value(x)}" for k, x in v.items())
    if isinstance(v, list):
        return ", ".join(_value(x) for x in v)
    return _cell(v)


def components_page(model: Model) -> str:
    """Every component, one heading each, with the requirements allocated to it."""
    allocated: Dict[str, list] = {}
    for rid, r in model.reqs.items():
        for cid in allocations(r):
            allocated.setdefault(cid, []).append(rid)
    lines = ["# Components", "",
             "> Generated by `tools/reqs/check.py` from `docs/architecture/components.yaml`; edit that "
             "file, not this page. Field meanings are at the top of the YAML.", "",
             f"{len(model.comps)} components. Requirements are allocated to these IDs.", ""]
    for cid, c in model.comps.items():
        lines += [f"## {cid}", "", f"**{_cell(c.get('name', ''))}**", "", "| | |", "|---|---|",
                  f"| Kind, subsystem, stage | {c.get('kind')}, {c.get('subsystem')}, from stage {c.get('stage')} |"]
        for key, label in (("location", "Where"), ("functions", "Does"), ("ports", "Ports"),
                           ("deployed_on", "Runs on (by stage)"), ("provides", "Provides"),
                           ("needs", "Needs"), ("supplied_by", "Supplied by")):
            if c.get(key):
                value = c[key]
                if key == "ports":
                    value = [f"{x.get('name')} ({x.get('protocol')})" for x in value]
                lines.append(f"| {label} | {_value(value)} |")
        page_path = component_page(model, cid)
        if page_path:
            lines.append(f"| Page | [{page_path.split('/', 2)[2]}]({page_path.split('/', 2)[2]}) |")
        lines.append(f"| Requirements | {_links(model, sorted(allocated.get(cid, [])), '../requirements/pages/')} |")
        lines.append("")
    return "\n".join(lines)


def render_all(model: Model) -> Dict[str, str]:
    """{file name: content} for every prefix with requirements, the events, and an index."""
    pages = {}
    index = ["# Requirements by subsystem", "", NOTE.format(file="docs/requirements/*.yaml"), "",
             "| Subsystem | Requirements |", "|---|---|"]
    for prefix, info in model.prefixes.items():
        count = sum(1 for rid in model.reqs if model.subsystem_of(rid) == prefix)
        if not count:
            continue
        name = f"{prefix.lower()}.md"
        pages[name] = page(model, prefix)
        index.append(f"| [{prefix} — {info['name']}]({name}) | {count} |")
    if model.events:
        pages[EVENTS_PAGE] = events_page(model)
        index += ["", f"Verification events: [VE]({EVENTS_PAGE}) ({len(model.events)})."]
    pages["README.md"] = "\n".join(index) + "\n"
    return pages
