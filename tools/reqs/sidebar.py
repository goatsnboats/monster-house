"""The docs site's menu: docs/_sidebar.md.

The gloss site makes an alphabetical menu when a project brings none, which buries the
system specification. This one starts with the top of the spec tree (ConOps, the system
requirements, the architecture) and then lists every other page, folder by folder, so a
new page shows up without anyone editing the menu. Generated by tools/reqs/check.py.
"""

from __future__ import annotations

from pathlib import Path

SIDEBAR = "docs/_sidebar.md"

# The top of the menu, in reading order: (page under docs/, label).
START = [
    ("conops.md", "Concept of operations"),
    ("requirements/pages/sys.md", "System requirements (SYS)"),
    ("architecture.md", "Architecture"),
    ("stage-0-plan.md", "Stage 0 plan"),
    ("TBD.md", "Open questions (TBD register)"),
]

# Then each folder, top of the spec tree first: (folder under docs/, label).
# A folder not listed here is added at the end, alphabetically.
FOLDERS = [
    ("requirements", "Requirements"),
    ("interfaces", "Interfaces (ICDs)"),
    ("architecture", "Architecture data"),
    ("reviews", "Design reviews"),
    ("results", "Build results"),
    ("decisions", "Decisions (ADRs)"),
    ("trades", "Trade studies"),
    ("reference", "Reference"),
    ("templates", "Templates"),
]

# Labels for sub-folders; any other is its name, capitalized.
SUBFOLDERS = {"pages": "By subsystem", "nodes": "Nodes (computers)", "software": "Software items",
              "srr": "SRR", "results": "Results"}


def title_of(path: Path) -> str:
    """The page's first "# " heading, else its file name."""
    try:
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.startswith("# "):
                return line[2:].strip()
    except (OSError, UnicodeDecodeError):
        pass
    return path.stem


def _order(rel: Path) -> list:
    # Tree order. Within a folder: its README first, then its own pages, then its sub-folders.
    return [(1, part) for part in rel.parts[:-1]] + [(0, rel.name != "README.md", rel.name)]


def _label(folder: str) -> str:
    if folder in SUBFOLDERS:
        return SUBFOLDERS[folder]
    return folder if folder != folder.lower() else folder.replace("-", " ").capitalize()


def _link(docs: Path, rel: Path) -> str:
    title = title_of(docs / rel).replace("<", "&lt;").replace(">", "&gt;")
    return f"[{title}](/{rel.as_posix()})"


def render(docs: Path) -> str:
    pages = sorted(p.relative_to(docs) for p in docs.rglob("*.md")
                   if not any(part.startswith((".", "_")) for part in p.relative_to(docs).parts))
    lines = ["<!-- Generated by tools/reqs/check.py (tools/reqs/sidebar.py); edit that, not this file. -->", "",
             "- [Home](/README.md)", "- Start here"]
    shown = set()
    for rel, label in START:
        if (docs / rel).exists():
            lines.append(f"  - [{label}](/{rel})")
            shown.add(Path(rel))
    for rel in pages:  # any other top-level page
        if len(rel.parts) == 1 and rel not in shown and rel.name != "README.md":
            lines.append(f"  - {_link(docs, rel)}")
    folders = FOLDERS + sorted((f, f.replace("-", " ").capitalize())
                               for f in {r.parts[0] for r in pages if len(r.parts) > 1}
                               if f not in dict(FOLDERS))
    for folder, label in folders:
        inside = sorted((r for r in pages if r.parts[0] == folder and r not in shown), key=_order)
        if not inside:
            continue
        lines.append(f"- {label}")
        group = None
        for rel in inside:
            # A sub-folder gets its own label line, with its pages under it.
            for depth in range(1, len(rel.parts) - 1):
                sub = rel.parts[:depth + 1]
                if group is None or tuple(group[:depth + 1]) != sub:
                    lines.append(f"{'  ' * depth}- {_label(sub[-1])}")
            group = rel.parts[:-1]
            indent = "  " * (len(rel.parts) - 1)
            lines.append(f"{indent}- {_link(docs, rel)}")
    return "\n".join(lines) + "\n"
