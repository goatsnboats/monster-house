"""Write docs/requirements/trace.md: matrix, diagrams and coverage.

The output is sorted and has no timestamps, so it only changes when the
requirements, components or ICDs change (a test checks it is up to date).
"""

from __future__ import annotations

import re
from collections import Counter

from tools.reqs import budget
from tools.reqs.checks import Finding, allocations, children_of, events_for, icd_end_names, icd_sides
from tools.reqs.load import Model

TYPE_ORDER = ["functional", "performance", "interface", "constraint"]


def render(model: Model, findings: list[Finding]) -> str:
    lines = [
        "# Traceability (generated, do not edit)",
        "",
        "> Generated by `tools/reqs/check.py` from `docs/requirements/*.yaml`,",
        "> `docs/architecture/components.yaml` and `docs/interfaces/`. To regenerate, run",
        "> `.venv/bin/python -m tools.reqs.check` from the repository root.",
        "",
    ]
    lines += _summary(model)
    lines += _coverage(model, findings)
    lines += _budgets(model)
    lines += _verification(model)
    lines += _matrix(model)
    lines += _allocation_diagrams(model)
    lines += _interface_diagram(model)
    return "\n".join(lines) + "\n"


def _cell(text) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _basis(r: dict) -> str:
    b = r.get("basis")
    if isinstance(b, dict):
        return f"{b.get('method')}: {b.get('ref')}"
    return "needed" if r.get("type") == "performance" else "—"


def _node(name: str) -> str:
    return name.replace("-", "_")


# ── Summary ─────────────────────────────────────────────────────────────────────

def _summary(model: Model) -> list[str]:
    counts = Counter((model.subsystem_of(rid), r.get("type")) for rid, r in model.reqs.items())
    lines = ["## Summary", "", "| Subsystem | " + " | ".join(TYPE_ORDER) + " | Total |",
             "|---" * (len(TYPE_ORDER) + 2) + "|"]
    for prefix, info in model.prefixes.items():
        row = [counts[(prefix, t)] for t in TYPE_ORDER]
        if sum(row) or prefix == "SYS":
            lines.append(f"| {prefix} {info['name']} | " + " | ".join(str(n) for n in row) + f" | {sum(row)} |")
    total = [sum(counts[(p, t)] for p in model.prefixes) for t in TYPE_ORDER]
    lines.append("| **All** | " + " | ".join(str(n) for n in total) + f" | **{sum(total)}** |")

    kinds = Counter(c.get("kind") for c in model.comps.values())
    statuses = Counter(i.get("status") for i in model.icds.values())
    lines += ["", f"**Components:** {len(model.comps)} ({kinds['part']} parts, {kinds['software']} software). "
              f"**ICDs:** {len(model.icds)} (" + ", ".join(f"{n} {s}" for s, n in sorted(statuses.items())) + ").", ""]
    return lines


# ── Coverage ────────────────────────────────────────────────────────────────────

def _coverage(model: Model, findings: list[Finding]) -> list[str]:
    reqs = {rid: r for rid, r in model.reqs.items() if r.get("status") != "deleted"}
    system = [rid for rid in reqs if rid.startswith("SYS-")]
    sub = [rid for rid in reqs if not rid.startswith("SYS-")]
    with_children = [rid for rid in system if children_of(model, rid)]
    allocated = [rid for rid in sub if allocations(reqs[rid]) and all(c in model.comps for c in allocations(reqs[rid]))]
    interface = [rid for rid in reqs if reqs[rid].get("type") == "interface"]
    with_icd = [rid for rid in interface if reqs[rid].get("icd") in model.icds]

    lines = ["## Coverage", "",
             "| Check | Result |", "|---|---|",
             f"| System requirements with children | {len(with_children)} of {len(system)} |",
             f"| Subsystem requirements allocated to a component | {len(allocated)} of {len(sub)} |",
             f"| Interface requirements with an ICD | {len(with_icd)} of {len(interface)} |"]
    side_gaps = [f for f in findings if f.level == "gap" and f.where.startswith("ICD-")]
    sides = sum(len(icd_sides(model, i)) for i in model.icds.values())
    lines.append(f"| ICD sides with an interface requirement | {sides - len(side_gaps)} of {sides} |")
    perf = [rid for rid in reqs if reqs[rid].get("type") == "performance"]
    based = [rid for rid in perf if reqs[rid].get("basis")]
    lines.append(f"| Performance requirements with a quantitative basis | {len(based)} of {len(perf)} |")
    if model.events:
        verified = [rid for rid in reqs if events_for(model, rid)]
        lines.append(f"| Requirements with a verification event | {len(verified)} of {len(reqs)} |")
    errors = [f for f in findings if f.level == "error"]
    lines.append(f"| Checker errors | {len(errors)} |")
    lines.append("")

    unallocated = sorted(cid for cid in model.comps
                         if not any(cid in allocations(r) for r in reqs.values()))
    if unallocated:
        lines += [f"**Components with no requirement yet** ({len(unallocated)}): "
                  + ", ".join(f"`{c}`" for c in unallocated), ""]
    for title, level in (("Gaps", "gap"), ("Warnings (ICD topics vs `shared/topics.py`)", "warning")):
        items = [f for f in findings if f.level == level]
        lines += [f"### {title} ({len(items)})", ""]
        lines += [f"- {f.where}: {_cell(f.message)}" for f in items] or ["None."]
        lines.append("")

    cited: dict[str, list[str]] = {}
    for rid, r in sorted(reqs.items()):
        for ref in sorted(set(_tbd_refs(r.get("text", "")))):
            cited.setdefault(ref, []).append(rid)
    lines += ["### TBDs cited by requirements", ""]
    lines += [f"- {ref}: {', '.join(ids)}" for ref, ids in sorted(cited.items())] or ["None."]
    lines.append("")
    return lines


def _tbd_refs(text: str) -> list[str]:
    return re.findall(r"TBD-\d{3}", str(text))


# ── Budgets ─────────────────────────────────────────────────────────────────────

def _budgets(model: Model) -> list[str]:
    rows = budget.evaluate(model)
    lines = ["## Budgets", "",
             "What each host provides vs what is deployed on or supplied by it, per stage "
             "(`tools/reqs/budget.py`).", ""]
    if not rows:
        return lines + ["No budgets declared yet.", ""]
    lines += ["| Host | Resource | Stages | Need | Have | Status | Needed by |", "|---|---|---|---|---|---|---|"]
    for b in rows:
        need = b.need if b.need is not None else "?"
        status = {"ok": "OK", "over": "**OVER**", "incomplete": "waiting for " + ", ".join(b.tbds)}[b.status]
        who = ", ".join(f"{cid} ({amount})" for cid, amount in b.consumers)
        lines.append(f"| {b.host} | {b.resource} | {b.stages} | {need} | {b.have} | {status} | {who} |")
    return lines + [""]


# ── Verification ────────────────────────────────────────────────────────────────

def _verification(model: Model) -> list[str]:
    if not model.events:
        return []
    lines = ["## Verification plan", "",
             "Events from `docs/requirements/verification.yaml`, by stage.", "",
             "| Event | Stage | Method | Name | Where | Requirements |", "|---|---|---|---|---|---|"]
    for eid, e in sorted(model.events.items(), key=lambda kv: (kv[1].get("stage", 9), kv[0])):
        covers = e.get("covers") or []
        lines.append(f"| {eid} | {e.get('stage')} | {e.get('method')} | {_cell(e.get('name', ''))} | "
                     f"{_cell(e.get('where', ''))} | {len(covers)}: {', '.join(covers)} |")
    return lines + [""]


# ── Matrix ──────────────────────────────────────────────────────────────────────

def _matrix(model: Model) -> list[str]:
    lines = ["## Requirements", ""]
    for prefix, info in model.prefixes.items():
        ids = sorted(rid for rid in model.reqs if model.subsystem_of(rid) == prefix)
        if not ids:
            continue
        lines += [f"### {prefix} — {info['name']}", ""]
        if prefix == "SYS":
            lines += ["| ID | Type | Stage | Status | Requirement | Children | Decomposition | Basis | Verify | Events |",
                      "|---|---|---|---|---|---|---|---|---|---|"]
            for rid in ids:
                r = model.reqs[rid]
                kids = ", ".join(children_of(model, rid)) or "—"
                lines.append(f"| {rid} | {r.get('type')} | {r.get('stage')} | {r.get('status')} | "
                             f"{_cell(r.get('text', ''))} | {kids} | {_cell(r.get('decomposition', '—'))} | "
                             f"{_basis(r)} | {r.get('verify')} | {', '.join(events_for(model, rid)) or '—'} |")
        else:
            lines += ["| ID | Type | Stage | Status | Requirement | Parents | Allocated to | Allocation rationale "
                      "| ICD | Basis | Verify | Events |",
                      "|---|---|---|---|---|---|---|---|---|---|---|---|"]
            for rid in ids:
                r = model.reqs[rid]
                lines.append(f"| {rid} | {r.get('type')} | {r.get('stage')} | {r.get('status')} | "
                             f"{_cell(r.get('text', ''))} | {', '.join(r.get('derives_from') or []) or '—'} | "
                             f"{', '.join(allocations(r)) or '—'} | {_cell(r.get('allocation_rationale', '—'))} | "
                             f"{r.get('icd', '—')} | {_basis(r)} | {r.get('verify')} | "
                             f"{', '.join(events_for(model, rid)) or '—'} |")
        lines.append("")
    return lines


# ── Diagrams ────────────────────────────────────────────────────────────────────

def _allocation_diagrams(model: Model) -> list[str]:
    lines = ["## Allocation", "",
             "System requirement → subsystem requirement → component, one diagram per subsystem.", ""]
    drawn = False
    for prefix, info in model.prefixes.items():
        ids = sorted(rid for rid in model.reqs if model.subsystem_of(rid) == prefix and prefix != "SYS")
        if not ids:
            continue
        drawn = True
        lines += [f"### {prefix} — {info['name']}", "", "```mermaid", "flowchart LR"]
        for rid in ids:
            r = model.reqs[rid]
            for parent in r.get("derives_from") or []:
                lines.append(f"  {_node(parent)}[{parent}] --> {_node(rid)}[{rid}]")
            for comp in allocations(r):
                lines.append(f"  {_node(rid)} -.-> c_{_node(comp)}([{comp}])")
        lines += ["```", ""]
    if not drawn:
        lines += ["No subsystem requirements yet.", ""]
    return lines


def _interface_diagram(model: Model) -> list[str]:
    lines = ["## Interfaces", "",
             "Each ICD joins the subsystems (or outside entities) at its ends.", "",
             "```mermaid", "flowchart LR"]
    for iid, icd in sorted(model.icds.items()):
        lines.append(f'  {_node(iid)}{{{{"{iid}<br/>{_cell(icd.get("title", ""))}"}}}}')
        groups = []
        for name in icd_end_names(icd):
            group = model.comps[name]["subsystem"] if name in model.comps else name
            if group not in groups:
                groups.append(group)
        for group in groups:
            label = f"{group} {model.prefixes[group]['name']}" if group in model.prefixes else group
            shape = f'["{label}"]' if group in model.prefixes else f'(["{label}"])'
            lines.append(f"  {_node(group)}{shape} --- {_node(iid)}")
    lines += ["```", ""]
    return lines
