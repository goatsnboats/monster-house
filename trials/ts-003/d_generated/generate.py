"""Option D: write messages.py from ICD-001, so the ICD is the only definition.

Run it after changing an ICD (in the real thing, the checker would run it, as it writes
trace.md). Nobody edits messages.py by hand; the drift test regenerates it and fails if
the file on disk is different.

    python generate.py            # write messages.py
    python generate.py --check    # exit 1 if messages.py is out of date
"""

from __future__ import annotations

import pprint
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import icd  # noqa: E402

OUT = Path(__file__).parent / "messages.py"
PY_TYPES = {"number": "float", "integer": "int", "string": "str", "boolean": "bool"}


def camel(message: str) -> str:
    """'target count' -> 'TargetCount'."""
    return "".join(word.capitalize() for word in message.split())


def class_name(message: str, choice: dict, several: bool) -> str:
    """Expression, Blink...; a oneOf choice gets its own name from title, or its keys."""
    base = camel(message)
    if not several:
        return base
    return choice.get("title") or base + "".join(k.capitalize() for k in choice["required"])


def py_type(sub: dict) -> str:
    if "enum" in sub:
        return "Literal[" + ", ".join(repr(v) for v in sub["enum"]) + "]"
    if sub["type"] == "array":
        return f"list[{py_type(sub['items'])}]"
    return PY_TYPES[sub["type"]]


def dataclass_source(name: str, schema: dict) -> str:
    lines = ["@dataclass", f"class {name}:"]
    required = set(schema.get("required", []))
    for key, sub in schema["properties"].items():
        default = "" if key in required else " = None"
        lines.append(f"    {key}: {py_type(sub)}{default}")
    return "\n".join(lines)


def source(messages: dict, icd_id: str = "ICD-001") -> str:
    messages = {name: m for name, m in messages.items() if "payload_schema" in m}  # e.g. HTTP pages
    parts = [
        f'"""{icd_id} messages. GENERATED by generate.py from the ICD: do not edit by hand."""',
        "",
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass",
        "from typing import Literal",
        "",
    ]
    classes = {}
    for message, m in messages.items():
        schema = m["payload_schema"]
        if schema.get("type") != "object" and "oneOf" not in schema:
            parts += [f"{camel(message)} = {py_type(schema)}", ""]
            continue
        choices = schema.get("oneOf", [schema])
        names = [class_name(message, c, len(choices) > 1) for c in choices]
        classes[message] = names
        for name, choice in zip(names, choices):
            parts += ["", dataclass_source(name, choice), ""]
    parts += ["", "CLASSES = {"]
    parts += [f"    {m!r}: ({', '.join(n)},)," for m, n in classes.items()]
    parts += ["}", "", "SCHEMAS = " + pprint.pformat(
        {name: m["payload_schema"] for name, m in messages.items()}, sort_dicts=False, width=88)]
    return "\n".join(parts) + "\n"


if __name__ == "__main__":
    text = source(icd.messages())
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text() == text else 1)
    OUT.write_text(text)
